namespace Lattice.Shared.DesignSystem.Semantics;

using System.Text;
using System.Text.RegularExpressions;

public sealed class TokenCssGenerator(TokenResolver resolver)
{
    private static readonly Regex IdentifierRegex = new(
        @"[^a-z0-9-]+", RegexOptions.Compiled | RegexOptions.CultureInvariant);

    public string Generate(
        SemanticTokenDocument doc,
        string themeName,
        string themeAttribute = "data-theme",
        IReadOnlyDictionary<string, string>? userOverrides = null)
    {
        ArgumentNullException.ThrowIfNull(doc);

        if (!doc.Themes.ContainsKey(themeName))
            throw new InvalidOperationException(
                $"Theme '{themeName}' is not declared in '{doc.Metadata.Id}'.");

        var theme = doc.Themes[themeName];
        var scope = NormalizeIdentifier(themeName);

        var builder = new StringBuilder();
        builder.AppendLine("/* AUTO-GENERATED BY LATTICE — DO NOT EDIT */");
        builder.AppendLine($"/* Semantic tokens: {doc.Metadata.Name} v{doc.Metadata.TokenVersion} */");
        builder.AppendLine($"/* Theme: {theme.Name} ({theme.Mode}) */");
        builder.AppendLine();

        builder.AppendLine($"[{themeAttribute}=\"{scope}\"] {{");

        foreach (var token in doc.Tokens)
        {
            var key = CssVariableName(token.Id);
            var value = FormatValue(
                token,
                resolver.Resolve(doc.Metadata.Id, token.Id, themeName, userOverrides));

            builder.AppendLine($"    --{key}: {value};");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string CssVariableName(string tokenId) =>
        NormalizeIdentifier(tokenId.Replace('.', '-'));

    private static string FormatValue(Token token, string value)
    {
        if (token.Type == "color" && Regex.IsMatch(value, @"^[a-z]+-\d+\.\d+$"))
            return $"var(--primitive-{value.Replace('.', '-')})";
        return value;
    }

    private static string NormalizeIdentifier(string value)
    {
        var lowered = value.ToLowerInvariant();
        var replaced = IdentifierRegex.Replace(lowered, "-");
        return Regex.Replace(replaced, "-+", "-").Trim('-');
    }
    
    
}