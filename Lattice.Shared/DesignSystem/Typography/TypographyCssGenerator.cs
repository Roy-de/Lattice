using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Lattice.Shared.DesignSystem.Typography.Model;

namespace Lattice.Shared.DesignSystem.Typography;

public sealed class TypographyCssGenerator(
    TypographyScssGeneratorOptions? options = null)
{
    private readonly TypographyScssGeneratorOptions _options =
        options ?? new TypographyScssGeneratorOptions();

    private static readonly Regex DimensionRegex = new(
        @"^\s*(-?(?:\d+(?:\.\d*)?|\.\d+))([a-zA-Z%]*)\s*$",
        RegexOptions.Compiled | RegexOptions.CultureInvariant);

    private const string NumericFontVariant  = "tabular-nums";
    private const string NumericFontFeatures = "\"ss01\", \"ss03\"";

    public string Generate(FontTheme theme)
    {
        ArgumentNullException.ThrowIfNull(theme);
        ValidateOptions();

        var builder = new StringBuilder();
        var themeName = NormalizeIdentifier(theme.Name);

        builder.AppendLine("/* AUTO-GENERATED BY LATTICE — DO NOT EDIT */");
        builder.AppendLine($"/* Typography theme: {theme.Name} */");
        if (!string.IsNullOrWhiteSpace(theme.Description))
            builder.AppendLine($"/* {theme.Description} */");
        builder.AppendLine();

        // ──────────────────────────────────────────────────────────────
        // 1. Theme scope — CSS custom properties
        // ──────────────────────────────────────────────────────────────
        builder.AppendLine($"[{_options.ThemeAttribute}=\"{themeName}\"] {{");

        foreach (var (styleName, style) in theme.TextStyles)
        {
            if (!theme.Fonts.ContainsKey(style.Family))
            {
                throw new InvalidOperationException(
                    $"Typography style '{styleName}' references " +
                    $"undefined font family '{style.Family}'.");
            }

            var key = StyleKey(styleName);
            var isNumeric = IsNumericStyle(styleName);

            builder.AppendLine($"    --{key}-font-family: {BuildFontFamily(style.Family)};");
            builder.AppendLine($"    --{key}-font-weight: {style.Weight};");
            builder.AppendLine($"    --{key}-font-size: {ResolveValue(style.Mobile.Size, style.Desktop.Size, styleName, "size")};");
            builder.AppendLine($"    --{key}-line-height: {ResolveValue(style.Mobile.LineHeight, style.Desktop.LineHeight, styleName, "line-height")};");
            builder.AppendLine($"    --{key}-letter-spacing: {ResolveValue(style.Mobile.LetterSpacing, style.Desktop.LetterSpacing, styleName, "letter-spacing")};");
            builder.AppendLine($"    --{key}-font-style: normal;");

            if (isNumeric)
            {
                builder.AppendLine($"    --{key}-font-variant-numeric: {NumericFontVariant};");
                builder.AppendLine($"    --{key}-font-feature-settings: {NumericFontFeatures};");
            }

            builder.AppendLine();
        }

        builder.AppendLine("}");
        builder.AppendLine();

        // ──────────────────────────────────────────────────────────────
        // 2. Utility classes — consume the custom properties
        // ──────────────────────────────────────────────────────────────
        foreach (var (styleName, _) in theme.TextStyles)
        {
            var normalized = NormalizeIdentifier(styleName);
            var key = StyleKey(styleName);
            var isNumeric = IsNumericStyle(styleName);

            builder.AppendLine($".{normalized} {{");
            builder.AppendLine($"    font-family: var(--{key}-font-family);");
            builder.AppendLine($"    font-weight: var(--{key}-font-weight);");
            builder.AppendLine($"    font-style: var(--{key}-font-style);");
            builder.AppendLine($"    font-size: var(--{key}-font-size);");
            builder.AppendLine($"    line-height: var(--{key}-line-height);");
            builder.AppendLine($"    letter-spacing: var(--{key}-letter-spacing);");

            if (isNumeric)
            {
                builder.AppendLine(
                    $"    font-variant-numeric: var(--{key}-font-variant-numeric);");
                builder.AppendLine(
                    $"    font-feature-settings: var(--{key}-font-feature-settings);");
            }

            builder.AppendLine("    -webkit-font-smoothing: antialiased;");
            builder.AppendLine("    -moz-osx-font-smoothing: grayscale;");
            builder.AppendLine("    text-rendering: optimizeLegibility;");
            builder.AppendLine("}");
            builder.AppendLine();
        }

        return builder.ToString();
    }

    // ──────────────────────────────────────────────────────────────────
    // Fluid clamp / dimension resolution
    // ──────────────────────────────────────────────────────────────────

    private string ResolveValue(
        string mobile,
        string desktop,
        string styleName,
        string property)
    {
        if (string.IsNullOrWhiteSpace(mobile) || string.IsNullOrWhiteSpace(desktop))
        {
            throw new InvalidOperationException(
                $"Typography style '{styleName}' has an empty {property} " +
                "on its mobile or desktop block.");
        }

        var m = mobile.Trim();
        var d = desktop.Trim();

        if (string.Equals(m, d, StringComparison.OrdinalIgnoreCase))
            return m;

        if (!_options.GenerateFluidTypography)
            return m;

        var min = ParseDimension(m, styleName, property);
        var max = ParseDimension(d, styleName, property);

        if (!string.Equals(min.Unit, max.Unit, StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidOperationException(
                $"Typography style '{styleName}' has mismatched {property} units: " +
                $"'{mobile}' vs '{desktop}'. Use compatible CSS units.");
        }

        var lo = Math.Min(min.Value, max.Value);
        var hi = Math.Max(min.Value, max.Value);

        // Interpolate relative units (em/rem/%) with the same formula — clamp
        // still works because em/rem resolve against a fluid font-size.
        var range = _options.MaximumViewportWidth - _options.MinimumViewportWidth;
        var slope = (max.Value - min.Value) / range * 100;
        var intercept = min.Value - slope * _options.MinimumViewportWidth / 100;
        var sign = intercept < 0 ? "-" : "+";

        return
            $"clamp({Format(lo)}{min.Unit}, " +
            $"calc({Format(slope)}vw {sign} {Format(Math.Abs(intercept))}{min.Unit}), " +
            $"{Format(hi)}{max.Unit})";
    }

    private static (double Value, string Unit) ParseDimension(
        string value,
        string styleName,
        string property)
    {
        var match = DimensionRegex.Match(value);

        if (!match.Success)
        {
            throw new InvalidOperationException(
                $"Typography style '{styleName}' has invalid {property} value: '{value}'.");
        }

        // Unit may be empty for unitless values (e.g. "0" for letter-spacing).
        var unit = match.Groups[2].Value;
        if (string.IsNullOrEmpty(unit) && match.Groups[1].Value is "0" or "0.0" or "-0")
            unit = string.Empty;

        return (
            double.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture),
            unit
        );
    }

    // ──────────────────────────────────────────────────────────────────
    // Helpers
    // ──────────────────────────────────────────────────────────────────

    private string BuildFontFamily(string family)
    {
        var primary = $"\"{family.Replace("\"", "\\\"")}\"";

        if (_options.FontFallbacks.TryGetValue(family, out var fallback)
            && !string.IsNullOrWhiteSpace(fallback))
        {
            return $"{primary}, {fallback}";
        }

        return $"{primary}, sans-serif";
    }

    private bool IsNumericStyle(string styleName)
    {
        foreach (var prefix in _options.NumericStylePrefixes)
        {
            if (!string.IsNullOrEmpty(prefix)
                && styleName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private string StyleKey(string styleName) =>
        $"{NormalizeIdentifier(styleName)}";

    private string Format(double value)
    {
        return Math.Round(value, _options.DecimalPrecision, MidpointRounding.AwayFromZero)
            .ToString($"F{_options.DecimalPrecision}", CultureInfo.InvariantCulture)
            .TrimEnd('0')
            .TrimEnd('.');
    }

    private static string NormalizeIdentifier(string value)
    {
        var result = new string(
            value.ToLowerInvariant()
                .Select(c => char.IsLetterOrDigit(c) || c == '-' ? c : '-')
                .ToArray());

        return Regex.Replace(result, "-+", "-").Trim('-');
    }

    private void ValidateOptions()
    {
        if (_options.MaximumViewportWidth <= _options.MinimumViewportWidth)
        {
            throw new InvalidOperationException(
                "MaximumViewportWidth must exceed MinimumViewportWidth.");
        }

        if (_options.DecimalPrecision is < 0 or > 10)
        {
            throw new InvalidOperationException(
                "DecimalPrecision must be between 0 and 10.");
        }
        if (string.IsNullOrWhiteSpace(_options.ThemeAttribute))
        {
            throw new InvalidOperationException(
                "ThemeAttribute must not be empty.");
        }
    }
}